/**
 * Builds the committed API snapshot (`openapi.json`) and the types generated
 * from it (`schema.ts`) from `@positrontanks/server`, for the `gen:api` script and
 * the drift test (docs/spec/cli-api.md, HTTP client). Development only: the
 * CLI itself never imports this module.
 *
 * Imports only packages, so `scripts/gen-api.js` can load it straight from
 * source with Node's type stripping.
 */

import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { defaultConfig, startServer } from "@positrontanks/server";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";

/** The OpenAPI document a Positron Tanks server built from this workspace serves at `/openapi.json`. */
export async function serverOpenApiDocument(): Promise<OpenAPI3> {
  const dir = await mkdtemp(join(tmpdir(), "positrontanks-openapi-"));
  const quiet = { info: () => undefined, error: () => undefined };
  try {
    const running = await startServer(
      { ...defaultConfig, host: "127.0.0.1", port: 0, databasePath: ":memory:", storage: { kind: "local", directory: dir } },
      { logger: quiet },
    );
    try {
      const response = await fetch(`${running.url}/openapi.json`);
      return (await response.json()) as OpenAPI3;
    } finally {
      await running.close();
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

/** The text of `openapi.json` for a document. */
export function snapshotText(document: OpenAPI3): string {
  return `${JSON.stringify(document, null, 2)}\n`;
}

/** The text of `schema.ts`: the document's types, from openapi-typescript. */
export async function schemaText(document: OpenAPI3): Promise<string> {
  const ast = await openapiTS(document);
  return `/**
 * Generated by openapi-typescript from openapi.json; do not edit.
 * Regenerate with \`pnpm --filter @positrontanks/cli gen:api\`.
 */

${astToString(ast)}`;
}
